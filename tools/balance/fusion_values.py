"""Compile relic fusion tuning into the runtime table."""
from pathlib import Path
from star_values import read_json

ROOT = Path(__file__).resolve().parents[2]
PATH = ROOT / "tools/balance/fusion.json"
OUTPUT = ROOT / "src/SodRpg.Core/Game/Balance/Fusion.Generated.cs"


def render_outputs():
    data = read_json(PATH)
    fields = (("maxLevel", "MaxLevel", 1, 100),
              ("statBonusPerLevelPct", "StatBonusPerLevelPct", 1, 100),
              ("shardsPerRarity", "ShardsPerRarity", 1, 1000000),
              ("uniqueTuningCost", "UniqueTuningCost", 0, 1000000))
    if set(data) != {"schemaVersion", *(key for key, _, _, _ in fields)} or data["schemaVersion"] != 1:
        raise ValueError("fusion: invalid schema")
    lines = ["// <auto-generated />",
             "// Source: tools/balance/fusion.json; regenerate with python tools/balance/gen_cs.py.",
             "namespace SodRpg.Core.Game", "{", "    internal static class FusionBalance", "    {"]
    for key, name, low, high in fields:
        value = data[key]
        if type(value) is not int or not low <= value <= high:
            raise ValueError("fusion." + key + ": expected integer in range")
        lines.append(f"        internal const int {name} = {value};")
    lines += ["    }", "}", ""]
    return {OUTPUT: "\n".join(lines)}

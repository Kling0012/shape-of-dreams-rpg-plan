"""Compile room omen tuning into the runtime table."""
import json
from pathlib import Path
from star_values import number, read_json

ROOT = Path(__file__).resolve().parents[2]
PATH = ROOT / "tools/balance/room-omens.json"
OUTPUT = ROOT / "src/SodRpg.Core/Game/Balance/RoomOmens.Generated.cs"
EFFECTS = ("Vigor", "Swiftness", "Focus", "Fortitude", "Healing", "Fortune",
           "Sluggishness", "Fragility", "Weariness", "Drought", "RestlessEnemies", "SturdyEnemies",
           "Vitality", "Alacrity", "Feebleness", "Dulling")


def render_outputs():
    data = read_json(PATH)
    if set(data) != {"schemaVersion", "blessingChance", "trialDropBonus", "defaultTrialScale", "trialScales", "effects", "coop"} or data["schemaVersion"] != 1:
        raise ValueError("room-omens: invalid schema")
    if set(data["effects"]) != set(EFFECTS):
        raise ValueError("room-omens.effects: unexpected keys")
    lines = ["// <auto-generated />", "// Source: tools/balance/room-omens.json; regenerate with python tools/balance/gen_cs.py.",
             "namespace SodRpg.Core.Game", "{", "    internal static class RoomOmenBalance", "    {"]
    for key, name, low, high in (("blessingChance", "BlessingChance", 0, 1),
                                 ("trialDropBonus", "TrialDropBonus", 0, 1),
                                 ("defaultTrialScale", "DefaultTrialScale", 0, 10)):
        value = number(data[key], "room-omens." + key)
        if not low <= value <= high:
            raise ValueError("room-omens." + key + ": out of range")
        lines.append(f"        internal const double {name} = {value}d;")
    coop = data["coop"]
    coop_fields = (("coopOmenChance", "CoopOmenChance", 0, 1),
                   ("wardReduction", "WardReduction", 0, 1),
                   ("resonanceWindow", "ResonanceWindow", 0.01, 60),
                   ("resonanceDuration", "ResonanceDuration", 0.01, 60),
                   ("resonanceVulnerable", "ResonanceVulnerable", 1, 10))
    if not isinstance(coop, dict) or set(coop) != {field[0] for field in coop_fields}:
        raise ValueError("room-omens.coop: unexpected keys")
    for key, name, low, high in coop_fields:
        value = number(coop[key], "room-omens.coop." + key)
        if not low <= value <= high:
            raise ValueError("room-omens.coop." + key + ": out of range")
        lines.append(f"        internal const double {name} = {value}d;")
    for name in EFFECTS:
        value = number(data["effects"][name], "room-omens.effects." + name)
        if not -100 <= value <= 100:
            raise ValueError("room-omens.effects: out of range")
        lines.append(f"        internal const double {name} = {value}d;")
    lines += ["        internal static double TrialScale(string key)", "        {", "            switch (key)", "            {"]
    if not isinstance(data["trialScales"], dict):
        raise ValueError("room-omens.trialScales: expected object")
    for key, raw in sorted(data["trialScales"].items()):
        value = number(raw, "room-omens.trialScales")
        if not key.startswith("Hero_") or not 0 <= value <= 10:
            raise ValueError("room-omens.trialScales: invalid entry")
        lines.append(f"                case {json.dumps(key)}: return {value}d;")
    lines += ["                default: return DefaultTrialScale;", "            }", "        }", "    }", "}", ""]
    return {OUTPUT: "\n".join(lines)}

"""Compile melee and cooperative distance tuning into the runtime table."""
from pathlib import Path
from decimal import Decimal
from star_values import read_json

ROOT = Path(__file__).resolve().parents[2]
PATH = ROOT / "tools/balance/coop.json"
OUTPUT = ROOT / "src/SodRpg.Core/Game/Balance/Coop.Generated.cs"


def render_outputs():
    data = read_json(PATH)
    fields = (("fullRange", "FullRange"), ("outerRange", "OuterRange"),
              ("graceSeconds", "GraceSeconds"),
              ("rangeToSpeedMultiplier", "RangeToSpeedMultiplier"),
              ("breakSeconds", "BreakSeconds"), ("breakDamagePercent", "BreakDamagePercent"),
              ("meleeGuardRange", "MeleeGuardRange"),
              ("meleeGuardReductionPercent", "MeleeGuardReductionPercent"),
              ("scanSeconds", "ScanSeconds"),
              ("autoCastIntervalSeconds", "AutoCastIntervalSeconds"),
              ("autoCastOwnHitSeconds", "AutoCastOwnHitSeconds"),
              ("autoCastAllyHitSeconds", "AutoCastAllyHitSeconds"))
    if set(data) != {"schemaVersion", *(key for key, _ in fields)} or data["schemaVersion"] != 1:
        raise ValueError("coop: invalid schema")
    lines = ["// <auto-generated />",
             "// Source: tools/balance/coop.json; regenerate with python tools/balance/gen_cs.py.",
             "namespace SodRpg.Core.Game", "{", "    public static class CoopBalance", "    {"]
    for key, name in fields:
        value = data[key]
        if type(value) not in (int, Decimal) or not 0 < value <= 100:
            raise ValueError("coop." + key + ": expected positive number <= 100")
        lines.append(f"        public const float {name} = {value:g}f;")
        # Constant text for attribute labels (C# 9 cannot format numbers into constants).
        lines.append(f'        public const string {name}Text = "{value:g}";')
    if data["outerRange"] <= data["fullRange"] or data["meleeGuardReductionPercent"] >= 100:
        raise ValueError("coop: invalid distance or reduction")
    lines += ["    }", "}", ""]
    return {OUTPUT: "\n".join(lines)}

"""Compile native essence limits and independent feature switches."""
from decimal import Decimal
from pathlib import Path
from star_values import read_json

ROOT = Path(__file__).resolve().parents[2]
PATH = ROOT / "tools/balance/essence-caps.json"
OUTPUT = ROOT / "src/SodRpg.Core/Game/Balance/EssenceCaps.Generated.cs"


def render_outputs():
    data = read_json(PATH)
    fields = {
        "qualitySoftCap": (("threshold", "QualityThreshold", 0, 1000000),
                           ("excessDivisor", "QualityExcessDivisor", 1, 1000000)),
        "ricochet": (("maxChance", "RicochetMaxChance", 0, 1),),
        "fever": (("maxDamageAmplification", "FeverMaxDamageAmplification", 0, 100),),
        "embertail": (("maxCooldownReduction", "EmbertailMaxCooldownReduction", 0, 1),),
        "epiphany": (("maxRefundFraction", "EpiphanyMaxRefundFraction", 0, 1),),
        "memoryReuse": (("baseCooldownFraction", "MemoryReuseBaseCooldownFraction", 0, 1),
                        ("minimumSeconds", "MemoryReuseMinimumSeconds", 0, 60)),
        "crystalCircuit": (("internalCooldownSeconds", "CrystalCircuitInternalCooldownSeconds", 0, 60),),
        "memoryHaste": (("maxRemainingCooldownPercent", "MemoryHasteMaxRemainingCooldownPercent", 0, 100),),
    }
    if set(data) != {"schemaVersion", *fields} or type(data["schemaVersion"]) is not int or data["schemaVersion"] != 1:
        raise ValueError("essence-caps: invalid schema")
    lines = ["// <auto-generated />",
             "// Source: tools/balance/essence-caps.json; regenerate with python tools/balance/gen_cs.py.",
             "namespace SodRpg.Core.Game", "{", "    internal static class EssenceCapsBalance", "    {"]
    for key, entries in fields.items():
        section = data[key]
        if not isinstance(section, dict) or set(section) != {"enabled", *(field for field, _, _, _ in entries)}:
            raise ValueError("essence-caps." + key + ": invalid fields")
        if type(section["enabled"]) is not bool:
            raise ValueError("essence-caps." + key + ".enabled: expected boolean")
        name = key[0].upper() + key[1:] + "Enabled"
        lines.append(f"        internal static readonly bool {name} = {str(section['enabled']).lower()};")
        for field, name, low, high in entries:
            value = section[field]
            if type(value) not in (int, Decimal) or not Decimal(value).is_finite() or not low <= value <= high:
                raise ValueError(f"essence-caps.{key}.{field}: expected finite number in [{low}, {high}]")
            lines.append(f"        internal const float {name} = {float(value):.9g}f;")
    lines += ["    }", "}", ""]
    return {OUTPUT: "\n".join(lines)}

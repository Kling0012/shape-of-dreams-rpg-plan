"""Compile forbidden-smith / nemesis tuning (issues #415/#423) into the runtime table.

All values are provisional first-pass numbers (issue #423): adjust forbidden.json
and regenerate with gen_cs.py; actual playtesting decides the final tuning.
pactVariants must stay at exactly four stat pairs: the fifth pact is the fixed
save-format variant "Blood Transmutation" (Forbidden.TransmuteVariant == 4).
"""
import json
from pathlib import Path
from star_values import number, read_json

ROOT = Path(__file__).resolve().parents[2]
PATH = ROOT / "tools/balance/forbidden.json"
OUTPUT = ROOT / "src/SodRpg.Core/Game/Balance/ForbiddenBalance.Generated.cs"
# Stat identifiers as written in the Stat enum; emitted by name, never by value.
STATS = ("AttackPct", "PowerPct", "AttackSpeedPct", "CritDamagePct", "MaxHealthPct",
         "Armor", "Haste", "MoveSpeedPct")
INTS = (
    ("forbid.coreCost", "ForbidCoreCost", 1, 99),
    ("forbid.shardCost", "ForbidShardCost", 0, 100000),
    ("forbid.tuningCost", "ForbidTuningCost", 0, 999),
    ("forbid.orangeRetuneBonus", "OrangeRetuneBonus", 0, 20),
    ("patterns.overchargePowerPct", "OverchargePowerPct", 100, 1000),
    ("patterns.overchargeAffixFallbackPct", "OverchargeAffixFallbackPct", 100, 1000),
    ("patterns.ruinAffixPct", "RuinAffixPct", 100, 1000),
    ("patterns.ruinMaxHealthPct", "RuinMaxHealthPct", -95, -1),
    ("patterns.maxHealthPctFloor", "MaxHealthPctFloor", -95, -1),
    ("transmute.healPct", "TransmuteHealPct", 1, 100),
    ("nemesis.bossHealthPct", "NemesisBossHealthPct", 0, 1000),
    ("nemesis.bossAttackPct", "NemesisBossAttackPct", 0, 1000),
    ("nemesis.miniBossHealthPct", "NemesisMiniBossHealthPct", 0, 1000),
    ("nemesis.miniBossAttackPct", "NemesisMiniBossAttackPct", 0, 1000),
    ("nemesis.armor", "NemesisArmor", 0, 1000),
    ("nemesis.bossCores", "NemesisBossCores", 0, 10),
    ("nemesis.shardBonusPct", "NemesisShardBonusPct", 0, 10000),
    ("nemesis.tuningBonus", "NemesisTuningBonus", 0, 999),
    ("grudge.maximum", "MaxGrudge", 1, 10),
    ("grudge.chanceStepPct", "GrudgeChanceStepPct", 0, 1000),
    ("grudge.healthStepPct", "GrudgeHealthStepPct", 0, 1000),
    ("grudge.attackStepPct", "GrudgeAttackStepPct", 0, 1000),
    ("grudge.bonusCoreAt", "GrudgeBonusCoreAt", 0, 10),
)
DOUBLES = (("nemesis.bossChance", "BossNemesisChance", 0, 1),
           ("nemesis.miniBossChance", "MiniBossNemesisChance", 0, 1))
FLOATS = (("transmute.attackPerHealthPct", "TransmuteAttackPerHealthPct", 0, 100),
          ("transmute.attackCap", "TransmuteAttackCap", 0, 1000),
          ("transmute.durationSeconds", "TransmuteDuration", 0.1, 600))


def _canonical(value):
    return format(number(value, "forbidden").normalize(), "f")


def _section(data, path):
    keys = path.split(".")
    for key in keys:
        if not isinstance(data, dict) or key not in data:
            raise ValueError(f"forbidden.{path}: expected an object with {key}")
        data = data[key]
    return data


def render_outputs():
    data = read_json(PATH)
    if set(data) != {"schemaVersion", "smith", "forbid", "patterns", "pactVariants",
                     "transmute", "nemesis", "grudge"} or data["schemaVersion"] != 1:
        raise ValueError("forbidden: invalid schema")
    lines = ["// <auto-generated />", "// Source: tools/balance/forbidden.json; regenerate with python tools/balance/gen_cs.py.",
             "namespace SodRpg.Core.Game", "{", "    internal static class ForbiddenBalance", "    {"]
    tiers = data["smith"]["tiers"]
    if not isinstance(tiers, list) or not 1 <= len(tiers) <= 4:
        raise ValueError("forbidden.smith.tiers: expected 1..4 levels")
    costs = []
    for tier in tiers:
        if not isinstance(tier, dict) or set(tier) != {"shards", "tuning"}:
            raise ValueError("forbidden.smith.tiers[]: expected exactly shards, tuning")
        shards = number(tier["shards"], "forbidden.smith.tiers.shards")
        tuning = number(tier["tuning"], "forbidden.smith.tiers.tuning")
        if not 0 <= shards <= 1000000 or not 0 <= tuning <= 9999:
            raise ValueError("forbidden.smith.tiers[]: out of range")
        costs.append(f"({_canonical(shards)}, {_canonical(tuning)})")
    lines.append(f"        internal static readonly (int Shards, int Tuning)[] SmithCosts = {{ {', '.join(costs)} }};")
    for path, name, low, high in INTS:
        raw = _section(data, path)
        # Integers must be written as JSON ints; bool is not an int here.
        if type(raw) is not int or not low <= raw <= high:
            raise ValueError(f"forbidden.{path}: expected integer {low}..{high}")
        lines.append(f"        internal const int {name} = {_canonical(raw)};")
    for path, name, low, high in DOUBLES:
        value = number(_section(data, path), "forbidden." + path)
        if not low <= value <= high:
            raise ValueError(f"forbidden.{path}: expected {low}..{high}")
        lines.append(f"        internal const double {name} = {_canonical(value)}d;")
    for path, name, low, high in FLOATS:
        value = number(_section(data, path), "forbidden." + path)
        if not low <= value <= high:
            raise ValueError(f"forbidden.{path}: expected {low}..{high}")
        lines.append(f"        internal const float {name} = {_canonical(value)}f;")
    variants = data["pactVariants"]
    # Exactly four pairs: the transmute pact is fixed at index 4 in the save format.
    if not isinstance(variants, list) or len(variants) != 4:
        raise ValueError("forbidden.pactVariants: expected exactly four stat pairs")
    pairs = []
    for variant in variants:
        if not isinstance(variant, dict) or set(variant) != {"boonStat", "boon", "baneStat", "bane"}:
            raise ValueError("forbidden.pactVariants[]: expected exactly boonStat, boon, baneStat, bane")
        for role in ("boon", "bane"):
            stat = variant[role + "Stat"]
            if stat not in STATS:
                raise ValueError(f"forbidden.pactVariants[].{role}Stat: unknown stat {stat!r}")
        boon = variant["boon"]
        bane = variant["bane"]
        if type(boon) is not int or not 1 <= boon <= 1000:
            raise ValueError("forbidden.pactVariants.boon: expected integer 1..1000")
        if type(bane) is not int or not -1000 <= bane <= -1:
            raise ValueError("forbidden.pactVariants.bane: expected integer -1000..-1")
        pairs.append(f"(new StatLine(Stat.{variant['boonStat']}, {_canonical(boon)}), "
                     f"new StatLine(Stat.{variant['baneStat']}, {_canonical(bane)}))")
    lines.append("        internal static readonly (StatLine Boon, StatLine Bane)[] PactVariants =")
    lines.append("        {")
    lines.extend(f"            {pair}," for pair in pairs)
    lines.append("        };")
    lines += ["    }", "}", ""]
    return {OUTPUT: "\n".join(lines)}
